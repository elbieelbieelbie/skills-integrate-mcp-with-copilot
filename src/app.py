"""
High School Management System API

A super simple FastAPI application that allows students to view and sign up
for extracurricular activities at Mergington High School.
"""

from fastapi import Depends, FastAPI, HTTPException
from fastapi.security import HTTPBasic, HTTPBasicCredentials
from fastapi.staticfiles import StaticFiles
from fastapi.responses import RedirectResponse
import hmac
import os
from pathlib import Path

app = FastAPI(title="Mergington High School API",
              description="API for viewing and signing up for extracurricular activities")

# Mount the static files directory
current_dir = Path(__file__).parent
app.mount("/static", StaticFiles(directory=os.path.join(Path(__file__).parent,
          "static")), name="static")

teacher_auth = HTTPBasic(auto_error=False)


def require_teacher(
    credentials: HTTPBasicCredentials | None = Depends(teacher_auth),
) -> None:
    """Require credentials configured for a teacher account."""
    username = os.getenv("TEACHER_USERNAME")
    password = os.getenv("TEACHER_PASSWORD")
    if not username or not password:
        raise HTTPException(
            status_code=503,
            detail="Teacher authentication is not configured",
        )

    valid_username = credentials is not None and hmac.compare_digest(
        credentials.username.encode("utf-8"), username.encode("utf-8")
    )
    valid_password = credentials is not None and hmac.compare_digest(
        credentials.password.encode("utf-8"), password.encode("utf-8")
    )
    if not valid_username or not valid_password:
        raise HTTPException(
            status_code=401,
            detail="Invalid teacher credentials",
            headers={"WWW-Authenticate": "Basic"},
        )


